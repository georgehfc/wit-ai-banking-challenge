// Turns ../design/tokens/tokens.json (DTCG) into src/styles/tokens.css.
// Primitives become --p-*, semantic light/dark become --*. Re-run after George changes tokens or Figma variables.
import { readFileSync, writeFileSync } from "node:fs";
const tokens = JSON.parse(readFileSync(new URL("../../design/tokens/tokens.json", import.meta.url)));
const flat = {};
(function walk(o, path) {
  if (o && typeof o === "object" && "$value" in o) { flat[path.join(".")] = o.$value; return; }
  for (const [k, v] of Object.entries(o || {})) if (!k.startsWith("$")) walk(v, [...path, k]);
})(tokens, []);
const resolve = (v) => {
  while (typeof v === "string" && v.startsWith("{")) v = flat[v.slice(1, -1)];
  if (v && typeof v === "object" && "hex" in v) return v.hex;
  if (v && typeof v === "object" && "value" in v) return `${v.value}${v.unit ?? ""}`;
  return String(v);
};
const name = (path, drop) => "--" + path.split(".").slice(drop).join("-");
const lines = (prefix, drop, extra = "") => Object.keys(flat).filter((p) => p.startsWith(prefix))
  .map((p) => `  ${extra}${name(p, drop)}: ${resolve(flat[p])};`).join("\n");
const prim = Object.keys(flat).filter((p) => p.startsWith("primitive."))
  .map((p) => `  --p-${p.split(".").slice(1).join("-")}: ${resolve(flat[p])};`).join("\n");
const css = `/* Generated by scripts/tokens-to-css.mjs from design/tokens/tokens.json. Don't edit by hand. */
:root {
${prim}
${lines("semantic.light.", 2)}
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${lines("semantic.dark.", 2, "  ")}
  }
}
:root[data-theme="dark"] {
${lines("semantic.dark.", 2)}
}
`;
writeFileSync(new URL("../src/styles/tokens.css", import.meta.url), css);
console.log(`tokens.css: ${Object.keys(flat).length} tokens`);
